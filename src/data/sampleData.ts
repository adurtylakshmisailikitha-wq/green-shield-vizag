export function findNearestVizagArea(lat: number, lng: number): VizagAreaInfo {
  let nearest = VIZAG_AREAS_DIRECTORY[0];
  let minDistanceSq = Number.MAX_VALUE;

  for (const area of VIZAG_AREAS_DIRECTORY) {
    const dLat = area.lat - lat;
    const dLng = area.lng - lng;
    const distSq = dLat * dLat + dLng * dLng;
    if (distSq < minDistanceSq) {
      minDistanceSq = distSq;
      nearest = area;
    }
  }

  return nearest;
}


